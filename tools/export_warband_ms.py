#!/usr/bin/env python3
"""
Export Ban-Sugoroku integration for Mount & Blade: Warband.

Generates build/warband_ban_sugoroku.py containing module_presentations
and module_scripts tuples that can be merged into a Warband ModuleSystem.
"""

from pathlib import Path

PROJECT_ROOT = Path(__file__).parent.parent
BUILD_DIR = PROJECT_ROOT / "build"

PRESENTATION = '''
("prsnt_ban_sugoroku", 0, mesh_load_window, [
    (ti_on_presentation_load, [
        (set_fixed_point_multiplier, 1000),
        (presentation_set_duration, 999999),
        (create_mesh_overlay, reg0, "mesh_ban_sugoroku_board"),
        (position_set_x, pos1, 500),
        (position_set_y, pos1, 350),
        (overlay_set_position, reg0, pos1),
        (overlay_set_scale, reg0, 1500),
        (str_store_string, s1, "@盤双六"),
        (create_text_overlay, reg1, s1, tf_center),
        (position_set_x, pos1, 500),
        (position_set_y, pos1, 650),
        (overlay_set_position, reg1, pos1),
    ]),
    (ti_on_presentation_run, [
        (store_trigger_param_1, ":dt"),
        (try_begin),
            (key_clicked, key_escape),
            (presentation_set_duration, 0),
        (try_end),
    ]),
])
'''

SCRIPTS = '''
("script_ban_sugoroku_init", [
    (store_script_param, ":mode", 1),
    (set_fixed_point_multiplier, 1000),
    # Initialise board state in global registers / slots
    (assign, "$bs_turn", 0),
    (assign, "$bs_mode", ":mode"),
    (assign, "$bs_bar_black", 0),
    (assign, "$bs_bar_white", 0),
    (assign, "$bs_borne_black", 0),
    (assign, "$bs_borne_white", 0),
]),

("script_ban_sugoroku_roll", [
    (store_random_in_range, ":d1", 1, 7),
    (store_random_in_range, ":d2", 1, 7),
    (assign, "$bs_dice1", ":d1"),
    (assign, "$bs_dice2", ":d2"),
    (val_add, "$bs_dice1", 0),
    (val_add, "$bs_dice2", 0),
]),

("script_ban_sugoroku_move", [
    (store_script_param, ":from", 1),
    (store_script_param, ":to", 2),
    (store_script_param, ":die", 3),
    # Placeholder movement logic; integrate with your board slots
    (assign, "$bs_last_from", ":from"),
    (assign, "$bs_last_to", ":to"),
    (assign, "$bs_last_die", ":die"),
    (val_add, "$bs_turn", 1),
    (val_mod, "$bs_turn", 2),
]),
'''


def main():
    BUILD_DIR.mkdir(parents=True, exist_ok=True)
    output = BUILD_DIR / "warband_ban_sugoroku.py"
    content = (
        "# Auto-generated by tools/export_warband_ms.py\n"
        "# Merge these tuples into module_presentations.py and module_scripts.py\n\n"
        "ban_sugoroku_presentations = [\n" + PRESENTATION + "]\n\n"
        "ban_sugoroku_scripts = [\n" + SCRIPTS + "]\n"
    )
    output.write_text(content)
    print(f"Generated {output}")
    print("Merge the tuples into your Warband ModuleSystem files.")


if __name__ == "__main__":
    main()